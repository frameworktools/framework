# Records the SHA-256 of every SKILL.md version the package has shipped, from
# git history, in inst/templates/skill-history.json. ai_skills_update() and
# upgrade() use it to recognize an unedited skill installed by an older
# version (before .framework/skills.lock.json existed) and update it rather
# than keep it as locally edited. Run from the package root after changing a
# skill, before release:  Rscript data-raw/skill_history.R

skills_dir <- file.path("inst", "templates", "skills")
history <- list()
for (skill in sort(list.dirs(skills_dir, full.names = FALSE, recursive = FALSE))) {
  path <- file.path(skills_dir, skill, "SKILL.md")
  commits <- system2("git", c("log", "--format=%H", "--", shQuote(path)), stdout = TRUE)
  hashes <- character()
  for (commit in commits) {
    tmp <- tempfile()
    status <- system2("git", c("show", shQuote(paste0(commit, ":", path))), stdout = tmp, stderr = FALSE)
    if (identical(as.integer(status), 0L)) {
      hashes <- c(hashes, as.character(openssl::sha256(file(tmp))))
    }
    unlink(tmp)
  }
  hashes <- c(hashes, as.character(openssl::sha256(file(path))))
  history[[skill]] <- sort(unique(hashes))
}
record <- list(
  description = paste(
    "SHA-256 of every SKILL.md the framework package has shipped, per skill.",
    "Generated by data-raw/skill_history.R; shared with framework-py."
  ),
  skills = history
)
writeLines(jsonlite::toJSON(record, pretty = TRUE, auto_unbox = TRUE),
           file.path("inst", "templates", "skill-history.json"))
