# Records the bundle hash of every version of each built-in skill the package
# has shipped, from git history, in inst/templates/skill-history.json
# (schema 2, per variant). pull_skills() and upgrade() add these to a
# built-in's known hashes, so an unedited copy installed by an older version
# (before .framework/skills.lock.json existed, or restored from git) is
# updated rather than kept as locally edited. Every shipped built-in is
# SKILL.md only, so each bundle is one SKILL.md. Run from the package root
# after changing a skill, before release:  Rscript data-raw/skill_history.R
# See docs/architecture/skills-lock-v2.md ("Known hashes").

# The bundle hash (framework-skill-bundle-v1), from R/skill_sync.R
bundle <- new.env()
sys.source(file.path("R", "skill_sync.R"), envir = bundle)
hash_skill_md <- function(raw) {
  files <- list(list(path = "SKILL.md", content = jsonlite::base64_enc(raw), executable = FALSE))
  bundle$.skill_hash(files)
}

variant <- "r"
skills_dir <- file.path("inst", "templates", "skills")
history <- list()
for (skill in sort(list.dirs(skills_dir, full.names = FALSE, recursive = FALSE))) {
  path <- file.path(skills_dir, skill, "SKILL.md")
  commits <- system2("git", c("log", "--format=%H", "--", shQuote(path)), stdout = TRUE)
  hashes <- character()
  for (commit in commits) {
    tmp <- tempfile()
    status <- system2("git", c("show", shQuote(paste0(commit, ":", path))), stdout = tmp, stderr = FALSE)
    if (identical(as.integer(status), 0L)) {
      hashes <- c(hashes, hash_skill_md(readBin(tmp, "raw", n = file.info(tmp)$size)))
    }
    unlink(tmp)
  }
  hashes <- c(hashes, hash_skill_md(readBin(path, "raw", n = file.info(path)$size)))
  history[[skill]] <- stats::setNames(list(as.list(sort(unique(hashes), method = "radix"))), variant)
}
record <- list(
  schema = 2L,
  description = paste(
    "Bundle hash of every version of each built-in skill the framework package has shipped, per skill and variant.",
    "Generated by data-raw/skill_history.R."
  ),
  skills = history
)
writeLines(jsonlite::toJSON(record, pretty = TRUE, auto_unbox = TRUE),
           file.path("inst", "templates", "skill-history.json"))
