#' Generate Quarto YAML Configuration
#'
#' @description
#' Generates `_quarto.yml` configuration files for Quarto projects.
#' Files are generated once on project creation and owned by the user thereafter.
#'
#' @param settings List containing Quarto settings (html and/or revealjs format configs)
#' @param format Character. Either "html" or "revealjs"
#' @param project_root Logical. If TRUE, generates project-level config. Default FALSE.
#' @param output_dir Optional output directory for rendered files (relative to file location)
#' 
#' @return Character vector of YAML lines
#' 
#' @details
#' Generated files include:
#' - Auto-generated header comment
#' - Format-specific settings from global defaults or project overrides
#' - Proper YAML structure compatible with Quarto
#'
#' Files are never automatically regenerated to preserve user edits.
#'
#' @keywords internal
#' @noRd
generate_quarto_yml <- function(settings, format = "html", project_root = FALSE, output_dir = NULL) {
  if (!format %in% c("html", "revealjs")) {
    stop("Format must be 'html' or 'revealjs'")
  }

  # Get format-specific settings
  format_settings <- settings[[format]]
  if (is.null(format_settings)) {
    # Fallback to defaults
    format_settings <- get_default_quarto_settings(format)
  }

  # Build header comment
  header <- c(
    "# Auto-generated by Framework on {date}",
    "# This file is yours to customize - Framework will not modify it after creation",
    "# framework::quarto_regenerate() adds missing keys only; overwrite = TRUE replaces it",
    ""
  )
  header <- gsub("\\{date\\}", format(Sys.Date(), "%Y-%m-%d"), header)

  # Build YAML structure
  yaml_lines <- character(0)

  # Project block (root gets type, children may still need output-dir)
  if (project_root || !is.null(output_dir)) {
    yaml_lines <- c(yaml_lines, "project:")
    if (project_root) {
      yaml_lines <- c(yaml_lines, "  type: default")
    }
    if (!is.null(output_dir) && nzchar(output_dir)) {
      yaml_lines <- c(yaml_lines, sprintf("  output-dir: %s", output_dir))
    }
    yaml_lines <- c(yaml_lines, "")
  }

  yaml_lines <- c(yaml_lines, "format:")

  if (format == "html") {
    yaml_lines <- c(
      yaml_lines,
      "  html:",
      sprintf("    theme: %s", format_settings$theme %||% "default"),
      sprintf("    toc: %s", tolower(as.character(format_settings$toc %||% TRUE))),
      sprintf("    toc-depth: %d", format_settings$toc_depth %||% 3),
      sprintf("    code-fold: %s", tolower(as.character(format_settings$code_fold %||% FALSE))),
      sprintf("    code-tools: %s", tolower(as.character(format_settings$code_tools %||% FALSE))),
      sprintf("    embed-resources: %s", tolower(as.character(format_settings$embed_resources %||% TRUE))),
      sprintf("    highlight-style: %s", format_settings$highlight_style %||% "github")
    )
  } else if (format == "revealjs") {
    yaml_lines <- c(
      yaml_lines,
      "  revealjs:",
      sprintf("    theme: %s", format_settings$theme %||% "default"),
      sprintf("    incremental: %s", tolower(as.character(format_settings$incremental %||% FALSE))),
      sprintf("    slide-number: %s", tolower(as.character(format_settings$slide_number %||% TRUE))),
      sprintf("    transition: %s", format_settings$transition %||% "slide"),
      sprintf("    background-transition: %s", format_settings$background_transition %||% "fade"),
      sprintf("    controls: %s", tolower(as.character(format_settings$controls %||% TRUE))),
      sprintf("    progress: %s", tolower(as.character(format_settings$progress %||% TRUE))),
      sprintf("    center: %s", tolower(as.character(format_settings$center %||% TRUE))),
      sprintf("    highlight-style: %s", format_settings$highlight_style %||% "github")
    )
  }

  # Combine header and content
  c(header, yaml_lines)
}

#' Get Default Quarto Settings
#'
#' @param format Character. Either "html" or "revealjs"
#' @return List of default settings for the format
#' @keywords internal
#' @noRd
get_default_quarto_settings <- function(format = "html") {
  if (format == "html") {
    list(
      format = "html",
      embed_resources = TRUE,
      theme = "default",
      toc = TRUE,
      toc_depth = 3,
      code_fold = FALSE,
      code_tools = FALSE,
      highlight_style = "github"
    )
  } else {
    list(
      format = "revealjs",
      theme = "default",
      incremental = FALSE,
      slide_number = TRUE,
      transition = "slide",
      background_transition = "fade",
      controls = TRUE,
      progress = TRUE,
      center = TRUE,
      highlight_style = "github"
    )
  }
}

#' Determine Format for Render Directory
#'
#' @param dir_key Character. Directory key name (e.g., "slides", "notebooks")
#' @param project_type Character. Project type ("project", "course", etc.)
#' @return Character. Either "html" or "revealjs"
#'
#' @details
#' Format selection rules:
#' - "slides" → revealjs
#' - All other directories → html
#' - Presentation project type at root → revealjs
#'
#' @keywords internal
#' @noRd
determine_render_format <- function(dir_key, project_type = NULL) {
  # Slides always use revealjs
  if (grepl("slides?", dir_key, ignore.case = TRUE)) {
    return("revealjs")
  }

  # Presentation project at root uses revealjs
  if (!is.null(project_type) && project_type == "presentation" && dir_key == "root") {
    return("revealjs")
  }

  # Everything else uses HTML
  "html"
}

#' Write Quarto Configuration File
#'
#' @param yaml_lines Character vector of YAML lines
#' @param path Character. Full path where to write the file
#' @return Logical. TRUE if successful, FALSE otherwise
#'
#' @keywords internal
#' @noRd
write_quarto_yml <- function(yaml_lines, path) {
  tryCatch({
    # Ensure directory exists
    dir_path <- dirname(path)
    if (!dir.exists(dir_path)) {
      dir.create(dir_path, recursive = TRUE, showWarnings = FALSE)
    }

    # Write file
    writeLines(yaml_lines, path)
    TRUE
  }, error = function(e) {
    warning("Failed to write _quarto.yml to ", path, ": ", e$message)
    FALSE
  })
}

#' Generate Quarto Configurations for Project
#'
#' @description
#' Main entry point for a project's Quarto configuration. Writes one root
#' `_quarto.yml` with the shared settings and an output folder that keeps
#' each render folder's path (notebooks/ renders to outputs/notebooks/). A
#' folder that needs its own format, such as a course's slides/, gets a
#' `_metadata.yml`, which inherits from the root. A render target outside the
#' shared output folder keeps its own `_quarto.yml`.
#'
#' @param project_path Character. Path to project root
#' @param project_type Character. One of "project", "project_sensitive", "course", "presentation"
#' @param render_dirs Named list. Render directories with their paths
#' @param quarto_settings List. Quarto settings (html and revealjs configs)
#' @param directories Named list. Source directories keyed the same as render_dirs
#' @param root_output_dir Ignored. Kept so older calls still work. The root
#'   output folder is the one most `render_dirs` share, as in the Python
#'   package. Setting it from `quarto.render_dir` would nest renders, such as
#'   `outputs/notebooks/notebooks/x.html`.
#' 
#' @return List with success status and paths of generated files
#' 
#' @export
quarto_generate_all <- function(project_path,
                                project_type,
                                render_dirs = NULL,
                                quarto_settings = NULL,
                                directories = NULL,
                                root_output_dir = NULL) {
  if (!dir.exists(project_path)) {
    stop("Project path does not exist: ", project_path)
  }

  generated_files <- character(0)
  # Render source folders exist, as Quarto expects
  for (pair in .quarto_render_pairs(render_dirs, directories)) {
    source_dir <- file.path(project_path, pair$source)
    if (!dir.exists(source_dir)) dir.create(source_dir, recursive = TRUE, showWarnings = FALSE)
  }
  for (file in .quarto_plan(project_type, render_dirs, quarto_settings, directories)) {
    path <- file.path(project_path, file$path)
    if (!identical(dirname(file$path), ".") && !dir.exists(dirname(path))) {
      dir.create(dirname(path), recursive = TRUE, showWarnings = FALSE)
    }
    if (write_quarto_yml(file$lines, path)) {
      generated_files <- c(generated_files, path)
    }
  }

  list(
    success = length(generated_files) > 0,
    files = generated_files,
    count = length(generated_files)
  )
}

# The Quarto files a project's settings call for, as a list of `path` (from
# the project root) and `lines`. See quarto_generate_all().
#' @keywords internal
#' @noRd
.quarto_plan <- function(project_type, render_dirs = NULL, quarto_settings = NULL, directories = NULL) {
  # Get quarto settings (from project or global defaults)
  if (is.null(quarto_settings) || (is.null(quarto_settings$html) && is.null(quarto_settings$revealjs))) {
    quarto_settings <- utils::modifyList(list(
      html = get_default_quarto_settings("html"),
      revealjs = get_default_quarto_settings("revealjs")
    ), quarto_settings %||% list())
  }

  # One Quarto project at the root holds the shared settings. Quarto keeps a
  # file's folder under the project's output-dir, so notebooks/x.qmd renders
  # to <output-dir>/notebooks/x.html. A folder whose render target is
  # <output-dir>/<folder> needs no file of its own; a folder that needs its
  # own format (slides) gets a _metadata.yml, which inherits from the root.
  pairs <- .quarto_render_pairs(render_dirs, directories)
  parents <- vapply(pairs, `[[`, "", "parent")
  fitting <- parents[!is.na(parents)]
  # The most common parent; ties go to the one first in byte order
  counts <- table(fitting)
  output_dir <- if (length(fitting) > 0) {
    candidates <- names(counts)[counts == max(counts)]
    sort(candidates, method = "radix")[1]
  }
  if (identical(output_dir, ".")) output_dir <- NULL

  root_format <- if (identical(project_type, "presentation")) "revealjs" else "html"
  files <- list(list(
    path = "_quarto.yml",
    lines = generate_quarto_yml(quarto_settings, format = root_format, project_root = TRUE, output_dir = output_dir)
  ))

  for (dir_key in names(pairs)) {
    pair <- pairs[[dir_key]]
    format <- determine_render_format(dir_key, project_type)
    fits <- identical(pair$parent, output_dir %||% ".")

    if (!fits) {
      # A render target outside the shared output folder: its own Quarto
      # project, as before, since output-dir is a project setting
      depth <- length(strsplit(pair$source, "/", fixed = TRUE)[[1]])
      output_dir_rel <- paste(c(rep("..", depth), pair$target), collapse = "/")
      files[[length(files) + 1]] <- list(
        path = file.path(pair$source, "_quarto.yml"),
        lines = generate_quarto_yml(quarto_settings, format = format, output_dir = output_dir_rel)
      )
    } else if (!identical(format, root_format)) {
      files[[length(files) + 1]] <- list(
        path = file.path(pair$source, "_metadata.yml"),
        lines = generate_quarto_yml(quarto_settings, format = format)
      )
    }
  }
  files
}

# Render folders with their source folder and the target's parent: "." when
# the target is the source itself, NA when it doesn't end in the source
#' @keywords internal
#' @noRd
.quarto_render_pairs <- function(render_dirs, directories) {
  pairs <- list()
  for (dir_key in names(render_dirs %||% list())) {
    target <- render_dirs[[dir_key]]
    source <- if (!is.null(directories) && dir_key %in% names(directories)) directories[[dir_key]] else dir_key
    if (!is.character(target) || !is.character(source) || !nzchar(target) || !nzchar(source)) next
    parent <- if (identical(target, source)) {
      "."
    } else if (endsWith(target, paste0("/", source))) {
      substr(target, 1, nchar(target) - nchar(source) - 1)
    } else {
      NA_character_
    }
    pairs[[dir_key]] <- list(source = source, target = target, parent = parent)
  }
  pairs
}

#' Regenerate Quarto Configurations
#'
#' @description
#' Brings a project's Quarto files in line with its settings: one root
#' `_quarto.yml`, plus a `_metadata.yml` or `_quarto.yml` for render folders
#' that need their own format or output folder.
#'
#' By default it never replaces your Quarto configuration. It creates the
#' files that are missing and, in a file that exists, at most adds the keys
#' Framework needs that it lacks (`project:`, `project: type:` and
#' `output-dir:`, and `format:` when there is none), keeping every other key,
#' value, and comment. Per-folder `_quarto.yml` files from older projects are
#' left in place and listed.
#'
#' With `overwrite = TRUE` it replaces the files with freshly generated ones
#' (your theme, `execute:`, and other custom keys are lost) and, with backups
#' on, removes the per-folder files that the root configuration replaces.
#' With `backup = FALSE` it never removes a file.
#'
#' Backups go to `.framework/backups/<timestamp>/`, which git ignores.
#'
#' @param project_path Character. Path to project root
#' @param backup Logical. If TRUE (default), copies each file before it is
#'   changed or removed.
#' @param overwrite Logical. If TRUE, replace existing Quarto files instead of
#'   adding missing keys. Default FALSE.
#' @param dry_run Logical. If TRUE, report what would change and change
#'   nothing.
#'
#' @return List with `success`, `regenerated` (files written), `unchanged`,
#'   `kept` (per-folder files left in place), `removed`, `backed_up`,
#'   `backup_location`, and `count`.
#'
#' @export
quarto_regenerate <- function(project_path, backup = TRUE, overwrite = FALSE, dry_run = FALSE) {
  checkmate::assert_flag(backup)
  checkmate::assert_flag(overwrite)
  checkmate::assert_flag(dry_run)
  if (!dir.exists(project_path)) {
    stop("Project path does not exist: ", project_path)
  }
  # Absolute, so paths still resolve after setwd(project_path) below
  project_path <- normalizePath(project_path, winslash = "/", mustWork = TRUE)

  settings_path <- file.path(project_path, "settings.yml")
  config_path <- if (file.exists(settings_path)) settings_path else file.path(project_path, "config.yml")
  if (!file.exists(settings_path) && !.fw_is_framework_config(config_path)) {
    stop("Project settings.yml/config.yml not found")
  }

  # Use settings_read() to properly resolve split files
  wd <- getwd()
  on.exit(setwd(wd), add = TRUE)
  setwd(project_path)
  config <- settings_read(config_path)

  changes <- .quarto_changes(
    project_path, config$project_type %||% "project", config$render_dirs, config$quarto,
    config$directories, overwrite = overwrite, remove_legacy = overwrite && backup
  )

  written <- names(changes$write)
  touched <- c(written[file.exists(file.path(project_path, written))], changes$remove)
  for (path in changes$kept) {
    message("Kept ", path, ": it makes ", dirname(path), "/ a separate Quarto project. ",
            "quarto_regenerate(overwrite = TRUE) folds it into the root _quarto.yml (backed up first).")
  }
  if (dry_run) {
    for (path in written) message("Would write ", path)
    for (path in changes$remove) message("Would remove ", path)
    return(invisible(list(success = TRUE, regenerated = written, unchanged = changes$unchanged,
                          kept = changes$kept, removed = changes$remove, backed_up = character(),
                          backup_location = NULL, count = length(written))))
  }

  backed_up <- character()
  backup_rel <- NULL
  if (backup && length(touched) > 0) {
    backup_rel <- .fw_backup_dir(project_path)
    backed_up <- .fw_backup_files(project_path, touched, backup_rel)
  }
  for (path in changes$remove) unlink(file.path(project_path, path))
  for (path in written) {
    target <- file.path(project_path, path)
    dir.create(dirname(target), recursive = TRUE, showWarnings = FALSE)
    write_quarto_yml(changes$write[[path]], target)
  }

  list(
    success = TRUE,
    backed_up = backed_up,
    backup_location = if (length(backed_up) > 0) file.path(project_path, backup_rel) else NULL,
    regenerated = file.path(project_path, written),
    unchanged = changes$unchanged,
    kept = changes$kept,
    removed = changes$remove,
    count = length(written)
  )
}

# What regenerating changes: `write` (path -> new lines), `unchanged`,
# `kept` (per-folder files left in place), and `remove`. Without overwrite,
# an existing file only gains missing keys (.quarto_add_missing_keys()).
#' @keywords internal
#' @noRd
.quarto_changes <- function(project_path, project_type, render_dirs, quarto_settings, directories,
                            overwrite = FALSE, remove_legacy = FALSE) {
  plan <- .quarto_plan(project_type, render_dirs, quarto_settings, directories)
  planned <- vapply(plan, `[[`, "", "path")

  # Projects made before one root config have a _quarto.yml in each render
  # folder. Each is a separate Quarto project that ignores the root.
  legacy <- character()
  for (dir_key in names(render_dirs %||% list())) {
    source <- directories[[dir_key]] %||% dir_key
    if (!is.character(source) || !nzchar(source) || identical(source, ".")) next
    for (name in c("_quarto.yml", "_metadata.yml")) {
      rel <- file.path(source, name)
      if (file.exists(file.path(project_path, rel)) && !rel %in% planned) legacy <- c(legacy, rel)
    }
  }
  # While those stay, the existing files keep the old layout as it is: an
  # output-dir added to the root would move where root documents render
  keep_layout <- length(legacy) > 0 && !remove_legacy

  write <- list()
  unchanged <- character()
  for (file in plan) {
    path <- file.path(project_path, file$path)
    if (!file.exists(path)) {
      write[[file$path]] <- file$lines
      next
    }
    current <- readLines(path, warn = FALSE)
    new <- if (overwrite) file$lines else if (keep_layout) current else .quarto_add_missing_keys(current, file$lines)
    if (identical(new, current)) unchanged <- c(unchanged, file$path) else write[[file$path]] <- new
  }
  list(
    write = write,
    unchanged = unchanged,
    kept = if (remove_legacy) character() else legacy,
    remove = if (remove_legacy) legacy else character()
  )
}

# A Quarto file's lines with the keys Framework needs and it lacks added:
# `project:`, `project: type:` and `project: output-dir:` (at the root),
# and `format:` when it has none. Other keys, values, and comments stay as
# they are. A file that isn't valid YAML is left alone.
#' @keywords internal
#' @noRd
.quarto_add_missing_keys <- function(current, generated) {
  have <- tryCatch(yaml::yaml.load(paste(current, collapse = "\n")), error = function(e) NULL)
  want <- yaml::yaml.load(paste(generated, collapse = "\n"))
  if (!is.null(have) && !is.list(have)) return(current)
  if (is.null(have)) {
    if (any(nzchar(trimws(sub("#.*$", "", current))))) return(current)
    have <- list()
  }
  lines <- current
  append_block <- function(key) {
    block <- yaml::as.yaml(stats::setNames(list(want[[key]]), key), indent.mapping.sequence = TRUE)
    block <- sub("\n$", "", block)
    if (length(lines) > 0 && nzchar(trimws(lines[length(lines)]))) lines <<- c(lines, "")
    lines <<- c(lines, strsplit(block, "\n", fixed = TRUE)[[1]])
  }
  if (!is.null(want$project)) {
    if (is.null(have$project)) {
      append_block("project")
    } else if (is.list(have$project)) {
      missing <- setdiff(names(want$project), names(have$project))
      if (length(missing) > 0) {
        at <- grep("^project:\\s*(#.*)?$", lines)[1]
        if (!is.na(at)) {
          child <- grep("^\\s+\\S", lines[-seq_len(at)], value = TRUE)[1]
          indent <- if (is.na(child)) "  " else sub("^(\\s+).*$", "\\1", child)
          added <- vapply(missing, function(k) paste0(indent, k, ": ", want$project[[k]]), "")
          lines <- append(lines, added, after = at)
        }
      }
    }
  }
  if (is.null(have$format) && !is.null(want$format)) append_block("format")
  lines
}

# Null-coalescing operator helper
`%||%` <- function(x, y) {
  if (is.null(x)) y else x
}
